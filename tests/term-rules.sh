def flatten(s):
    """줄바꿈과 줄 머리의 `>` · `#` 를 공백으로 바꿔 잇는다. 이은 글자마다 원래 줄 번호를 같이 낸다."""
    parts, lines, line, pos = [], [], 1, 0
    for m in re.finditer(r'\s*\n\s*(?:[>#]+\s*)?', s):
        seg = s[pos:m.start()]
        parts.append(seg)
        lines.extend([line] * len(seg))
        parts.append(' ')
        lines.append(line)
        line += m.group(0).count('\n')
        pos = m.end()
    seg = s[pos:]
    parts.append(seg)
    lines.extend([line] * len(seg))
    return ''.join(parts), lines


def find(flat):
    hits = []
    for name, pat in PATTERNS:
        for m in re.finditer(pat, flat):
            hits.append((name, m.start(), m.group(0)))
    for name, pat in WORDS:
        for m in re.finditer(r'(?<![가-힣])(?:' + pat + ')', flat):
            if name in EXCLUDE and re.match(EXCLUDE[name], m.group(0)):
                continue
            hits.append((name, m.start(), m.group(0)))
    return hits


def masked(s):
    flat, lines = flatten(s)
    for a in ALLOW:
        flat = flat.replace(a, ' ' * len(a))
    return flat, lines


