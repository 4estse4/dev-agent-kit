# 킷 파일이 킷이 쓰지 않기로 한 낱말을 쓰지 않는가 — 영어를 옮긴 동사 · 「지적」 · 「실측」과 구어 동사.
#
# 규칙은 킷 `CLAUDE.md` 의 「언어」 절에 있고, 여기는 그 규칙을 검사만 한다(이슈 #56).
# **바꿀 말은 검사가 정하지 않는다.** 한 낱말도 자리마다 뜻이 다르므로 찾아서 알리기만 한다.
#
# - 대상은 추적 파일 전부다. `docs/dev-log.md` 와 `tests/fixtures/` 는 그때의 기록이라 빼고,
#   이 파일은 찾는 말을 적어 두므로 뺀다
# - 줄바꿈과 줄 머리의 `>` · `#` 를 공백으로 바꿔 한 줄로 이은 뒤 찾는다. 낱말 사이에서 줄이
#   바뀐 자리도 검색 결과에 나온다. 찾은 자리는 원래 파일의 줄 번호로 모두 출력한다
# - `ALLOW` 의 글자를 먼저 지운 뒤 찾는다. 글자 그대로 일치하는 것만 허용한다. 「」 안에 쓴
#   낱말은 규칙에 적은 이름 그대로인 꼴만 허용하고, 「세웠다」처럼 글자가 다르면 허용하지 않는다
#
# 찾는 방식이 둘이다.
#
# `PATTERNS`(영어를 옮긴 동사 · 「지적」 · 「실측」) — 어간과 어미의 첫 글자까지 적고 그 뒤는 무엇이
# 와도 찾는다(「재면」이면 「재면서」도). 「서다」 · 「재다」는 어간 첫 음절로 시작하는 다른 낱말(서버 ·
# 설정 · 재고하다 · 재기동)이 너무 많아 `WORDS` 방식으로 찾을 수 없다. 끝까지 늘어놓은 목록은
# 「재보니」 · 「선 규칙」 · 「재고,」를 지나쳐서, 규칙을 어긴 자리가 남았는데도 통과했다. 넓히면서 두 번
# 예전 판이 찾던 꼴을 놓쳤다(「재 본」 · 「재면서」, 그다음 「재서야」 · 「재야겠다」). 한자어와 첫 두 글자가
# 같은 꼴(「재고 · 재기 · 재지 · 재서 · 재는 · 재야 · 재도」 — 재고하다 · 재기동 · 재지정 · 재서명 · 재도전 …)만
# 셋째 글자를 어미 글자 목록으로 좁히고, 뒤에 한글이 없으면 그대로 찾는다. 앞 글자가 한글이면 다른
# 낱말(「부재」 · 「문서면」 · 「앞세워」)이라 찾지 않는다.
#
# `WORDS`(구어 동사) — 어간의 첫 음절로 시작하는 낱말을 통째로 찾는다. **어미를 늘어놓지 않는다.**
# 어미를 늘어놓은 검색식은 늘어놓지 않은 꼴을 초록인 채 남겼다 — 위의 B1 이 그랬고, 이 방식을
# 계획하면서 만든 첫 검색식도 낱말마다 꼴을 놓쳤다(「깔므로」 · 「까는데」). 어간의 첫 음절은 활용해도
# 몇 개뿐이다. **활용해서 첫 음절이 바뀌는 꼴을 모두 적는다.** 받침 ㄴ · ㄹ · ㅁ · ㅂ 이 합쳐진 음절
# (「깐 · 깔 · 깖 · 깝」), ㄹ 이 떨어진 음절(「까는 · 까세요」), 어미의 모음과 합쳐진 음절(「치다」의
# 「쳐 · 쳤」, 「뜨다」의 「떠 · 떴」), 「르」가 줄어든 음절(「가르다」의 「갈라」)이 그 예다. 예는 닫힌
# 목록이 아니다 — 낱말을 더할 때 그 낱말의 활용을 늘어놓아 첫 음절이 몇 가지인지 본다. 처음 판은
# 「깖」을 빠뜨려서 명사형이 초록인 채 지나갔고(PR #118 1라운드 콜드 리뷰), 그 뒤 적은 「이 셋을 다
# 적는다」도 모음이 합쳐진 꼴을 빠뜨렸다(2라운드). 같은 글자로 시작하는 다른 낱말은 `EXCLUDE` 로 뺀다. 새로 쓴 다른 낱말이 검색 결과에
# 나오면 그 낱말을 이유와 함께 `EXCLUDE` 에 더한다 — 잘못 찾으면 빨간 결과로 보이고, 못 찾으면 아무도
# 모른다. 뒤에 한글이 오면 빼는 조건(`(?![가-힣])`)도 그 음절로 시작하는 다른 낱말이 흔할 때만 둔다.
# 처음 판은 다른 낱말이 없는 「도니 · 칠 · 뜰 · 뜸」에도 두어서 「도니까」 · 「칠지」를 놓쳤다(PR #133 1라운드
# 콜드 리뷰).
#
# **못 찾는 꼴이 있다.** 다른 낱말과 글자가 같아 일부러 빼 둔 것이다. 이 꼴은 리뷰가 본다.
#   · 실행한다는 뜻의 「돌아가다」 — 되돌아간다는 뜻의 「돌아가다」와 같아 `EXCLUDE` 가 뺀다
#   · 「도세요 · 돕니다」 — 「도」는 조사와, 「돕니다」는 「돕다」와 같다
#   · 「권하다」의 관형형 「권한」 — 명사 「권한」과 같다
#   · 「돈 · 침」 뒤에 어미가 붙은 꼴 — 뒤에 한글이 오면 「돈이」 · 「침묵」 같은 다른 낱말이라 찾지 않는다
