#!/usr/bin/env bash
# 킷 파일이 킷이 쓰지 않기로 한 낱말을 쓰지 않는가 — 영어를 옮긴 동사 · 「지적」 · 「실측」과 구어 동사.
#
# 규칙은 킷 `CLAUDE.md` 의 「언어」 절에 있고, 여기는 그 규칙을 검사만 한다(이슈 #56).
# **바꿀 말은 검사가 정하지 않는다.** 한 낱말도 자리마다 뜻이 다르므로 찾아서 알리기만 한다.
#
# - 대상은 추적 파일 전부다. `docs/dev-log.md` 와 `tests/fixtures/` 는 그때의 기록이라 빼고,
#   이 파일은 찾는 말을 적어 두므로 뺀다
# - 줄바꿈과 줄 머리의 `>` · `#` 를 공백으로 바꿔 한 줄로 이은 뒤 찾는다. 낱말 사이에서 줄이
#   바뀐 자리도 검색 결과에 나온다. 찾은 자리는 원래 파일의 줄 번호로 모두 출력한다
# - `ALLOW` 의 글자를 먼저 지운 뒤 찾는다. 글자 그대로 일치하는 것만 허용한다. 「」 안에 쓴
#   낱말은 규칙에 적은 이름 그대로인 꼴만 허용하고, 「세웠다」처럼 글자가 다르면 허용하지 않는다
#
# 찾는 방식이 둘이다.
#
# `PATTERNS`(영어를 옮긴 동사 · 「지적」 · 「실측」) — 어간과 어미의 첫 글자까지 적고 그 뒤는 무엇이
# 와도 찾는다(「재면」이면 「재면서」도). 「서다」 · 「재다」는 어간 첫 음절로 시작하는 다른 낱말(서버 ·
# 설정 · 재고하다 · 재기동)이 너무 많아 `WORDS` 방식으로 찾을 수 없다. 끝까지 늘어놓은 목록은
# 「재보니」 · 「선 규칙」 · 「재고,」를 지나쳐서, 규칙을 어긴 자리가 남았는데도 통과했다. 넓히면서 두 번
# 예전 판이 찾던 꼴을 놓쳤다(「재 본」 · 「재면서」, 그다음 「재서야」 · 「재야겠다」). 한자어와 첫 두 글자가
# 같은 꼴(「재고 · 재기 · 재지 · 재서 · 재는 · 재야 · 재도」 — 재고하다 · 재기동 · 재지정 · 재서명 · 재도전 …)만
# 셋째 글자를 어미 글자 목록으로 좁히고, 뒤에 한글이 없으면 그대로 찾는다. 앞 글자가 한글이면 다른
# 낱말(「부재」 · 「문서면」 · 「앞세워」)이라 찾지 않는다.
#
# `WORDS`(구어 동사) — 어간의 첫 음절로 시작하는 낱말을 통째로 찾는다. **어미를 늘어놓지 않는다.**
# 어미를 늘어놓은 검색식은 늘어놓지 않은 꼴을 초록인 채 남겼다 — 위의 B1 이 그랬고, 이 방식을
# 계획하면서 만든 첫 검색식도 낱말마다 꼴을 놓쳤다(「깔므로」 · 「까는데」). 어간의 첫 음절은 활용해도
# 몇 개뿐이다. **활용해서 첫 음절이 바뀌는 꼴을 모두 적는다.** 받침 ㄴ · ㄹ · ㅁ · ㅂ 이 합쳐진 음절
# (「깐 · 깔 · 깖 · 깝」), ㄹ 이 떨어진 음절(「까는 · 까세요」), 어미의 모음과 합쳐진 음절(「치다」의
# 「쳐 · 쳤」, 「뜨다」의 「떠 · 떴」), 「르」가 줄어든 음절(「가르다」의 「갈라」)이 그 예다. 예는 닫힌
# 목록이 아니다 — 낱말을 더할 때 그 낱말의 활용을 늘어놓아 첫 음절이 몇 가지인지 본다. 처음 판은
# 「깖」을 빠뜨려서 명사형이 초록인 채 지나갔고(PR #118 1라운드 콜드 리뷰), 그 뒤 적은 「이 셋을 다
# 적는다」도 모음이 합쳐진 꼴을 빠뜨렸다(2라운드). 같은 글자로 시작하는 다른 낱말은 `EXCLUDE` 로 뺀다. 새로 쓴 다른 낱말이 검색 결과에
# 나오면 그 낱말을 이유와 함께 `EXCLUDE` 에 더한다 — 잘못 찾으면 빨간 결과로 보이고, 못 찾으면 아무도
# 모른다.
#
# **검색식을 먼저 검사한다.** `MUST_FIND` 는 찾아야 하는 문장, `MUST_PASS` 는 찾으면 안 되는 문장이다.
# 검색식이 지금까지 놓친 꼴은 전부 `MUST_FIND` 에 넣는다. 둘 중 하나라도 틀리면 파일을 훑지 않고
# 실패한다 — 검색식이 틀렸으면 파일에서 찾은 결과를 믿을 수 없다.
set -u
KIT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$KIT" || exit 1
python3 - <<'PY'
import re, subprocess, sys

PATTERNS = [
    ('지적', r'지적'),
    ('서다', r'(?<![가-힣])(?:섰|섭니|서다|서면|서야|서지|서고|서게|서는|서던|서려|서니|선다'
             r'|설 (?=[가-힣])|선 (?=[가-힣]))'),
    ('세우다', r'(?<![가-힣])(?:세우|세운|세웠|세워|세울|세웁)'),
    ('받치다', r'받치|받쳐|받친|받칠|받쳤|받칩'),
    ('재다', r'(?<![가-힣])(?:쟀|잰|잴|잽|재어|재봐|재봤|재본|재볼|재보|재려|재면|재다|재니|재며|재던|재겠'
             r'|재 [보봐봤볼본]'
             r'|재(?:고|기|지|서|는|야|도)(?:만|도|요|지|데|가|니|는|야|라|겠|한|할|(?![가-힣])))'),
    ('실측', r'실측'),
]
# 어간의 첫 음절로 시작하는 낱말 전체. 앞에 한글이 오면 다른 낱말의 가운데라 찾지 않는다
WORDS = [
    ('깔다', r'깔[가-힣]*|깐[가-힣]*|깖[가-힣]*|깝[가-힣]*|까[가-힣]+'),
    ('뚫리다', r'뚫[가-힣]*'),
]
# 같은 글자로 시작하는 다른 낱말. 찾은 낱말의 앞부분이 이 식과 맞으면 뺀다
EXCLUDE = {
    '깔다': r'까지|까닭|깔끔',
}
ALLOW = [
    # `open-pr` 이 옮긴 사람의 말이다. 인용은 낱말을 바꾸지 않는다
    '"지적 받은데',
    # `tests/section-refs.sh` 의 옛 제목 목록이다. 옛 제목과 글자가 같아야 한다
    '어느 검사를 어디에 둘 것인가 — 실측으로 정한다',
    # 규칙을 설명하려고 「」 안에 쓴 낱말 자체
    '「지적」', '「서다」', '「세우다」', '「받치다」', '「재다」', '「실측」',
    '「깔다」', '「뚫리다」',
]
MUST_FIND = [
    ('지적', '리뷰의 지적을 받았다'),
    ('실측', '(실측)'),
    # 예전 판이 놓쳤던 꼴(B1)
    ('재다', '결과를 재보니 맞았다'), ('서다', '선 규칙이 있다'), ('재다', '시간을 재고, 적었다'),
    ('재다', '한 번 재 본 값'), ('재다', '한 번 재\n본 값'), ('재다', '시간을 재면서 봤다'), ('받치다', '근거가 받쳤다'),
    ('서다', '규칙이 서던 자리'), ('재다', '다시 재서야 알았다'), ('재다', '다시 재야겠다'),
    ('세우다', '계획을 세워라'),
    # 「깔다」 — 첫 검색식이 놓친 꼴(깔므로 · 까는데 · 까므로 · 깔게)을 포함한다
    ('깔다', 'Go 를 깐다'), ('깔다', '도구를 깔고'), ('깔다', '깔 Go'), ('깔다', 'setup-go 가 까는 것'),
    ('깔다', '패치 하나를 깔므로'), ('깔다', 'Go 를 까는데'), ('깔다', '그대로 까므로'),
    ('깔다', '도구를 깔게 된다'), ('깔다', 'Go 를 깝니다'), ('깔다', '거기 깔아둔다'),
    ('깔다', '시스템에 깔지 마라'), ('깔다', '패치 하나를\n# 깐다'), ('깔다', 'CI 가 Go 를 깖(실제로 확인함)'),
    ('깔다', '도구를 까세요'),
    ('뚫리다', '실제로 뚫려서'), ('뚫리다', '압축으로 뚫렸다'), ('뚫리다', '어떻게 뚫리는지'),
]
MUST_PASS = [
    # 앞의 방식이 일부러 찾지 않는 다른 낱말
    '서버를 설정한다', '선택한 설치', '부재', '재고하다', '재기동', '재지정', '재서명', '재도전',
    '문서면', '앞세워', '계획을 정하라',
    # `EXCLUDE` 의 낱말
    '여기까지', '`--no-verify` 까지', '까닭이 없다', '깔끔하다',
    # 다른 낱말의 가운데. 앞에 한글이 오면 찾지 않는다
    '색깔이 다르다', '꿰뚫어 본다',
    # 바꿀 말로 쓰는 말
    '설치한다', '설치할 Go', '패치 하나를 설치하므로', '우회된다', '압축 때문에 생겼다',
    '「깔다」', '「뚫리다」',
]
SKIP = {'docs/dev-log.md', 'tests/term-rules.sh'}


def flatten(s):
    """줄바꿈과 줄 머리의 `>` · `#` 를 공백으로 바꿔 잇는다. 이은 글자마다 원래 줄 번호를 같이 낸다."""
    parts, lines, line, pos = [], [], 1, 0
    for m in re.finditer(r'\s*\n\s*(?:[>#]+\s*)?', s):
        seg = s[pos:m.start()]
        parts.append(seg)
        lines.extend([line] * len(seg))
        parts.append(' ')
        lines.append(line)
        line += m.group(0).count('\n')
        pos = m.end()
    seg = s[pos:]
    parts.append(seg)
    lines.extend([line] * len(seg))
    return ''.join(parts), lines


def find(flat):
    hits = []
    for name, pat in PATTERNS:
        for m in re.finditer(pat, flat):
            hits.append((name, m.start(), m.group(0)))
    for name, pat in WORDS:
        for m in re.finditer(r'(?<![가-힣])(?:' + pat + ')', flat):
            if name in EXCLUDE and re.match(EXCLUDE[name], m.group(0)):
                continue
            hits.append((name, m.start(), m.group(0)))
    return hits


def masked(s):
    flat, lines = flatten(s)
    for a in ALLOW:
        flat = flat.replace(a, ' ' * len(a))
    return flat, lines


bad = []
for name, text in MUST_FIND:
    if not any(n == name for n, _, _ in find(flatten(text)[0])):
        bad.append('「%s」 검색식이 이 문장을 못 찾는다: %r' % (name, text))
for text in MUST_PASS:
    got = find(masked(text)[0])
    if got:
        bad.append('이 문장은 찾으면 안 되는데 「%s」 검색식이 「%s」를 찾았다: %r' % (got[0][0], got[0][2], text))
if bad:
    for b in bad:
        print('  ✗ ' + b)
    print('    검색식이 틀렸다. 파일은 훑지 않았다')
    sys.exit(1)

ls = subprocess.run(['git', '-c', 'core.quotePath=false', 'ls-files'],
                    capture_output=True, text=True).stdout.split('\n')
files = [f for f in ls if f and f not in SKIP and not f.startswith('tests/fixtures/')]
if not files:
    print('  ✗ 검사할 파일이 없다 — git ls-files 가 빈 목록을 냈다')
    sys.exit(1)

found = []
for f in files:
    flat, lines = masked(open(f, encoding='utf-8', errors='replace').read())
    for name, at, word in find(flat):
        found.append((name, '%s:%d' % (f, lines[at]), word))

names = [n for n, _ in PATTERNS] + [n for n, _ in WORDS]
for name in names:
    for _, where, word in (h for h in found if h[0] == name):
        print('  ✗ 「%s」 %s — 「%s」' % (name, where, word))
if found:
    print('    %d자리. 바꿀 말은 자리마다 뜻대로 정한다. 규칙은 CLAUDE.md 의 「언어」 절에 있다' % len(found))
    sys.exit(1)
print('  ✓ 쓰지 않기로 한 낱말이 없다(검색식 %d개 · 자체 검사 %d문장 · 파일 %d개)'
      % (len(names), len(MUST_FIND) + len(MUST_PASS), len(files)))
